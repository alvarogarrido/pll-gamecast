/**
 * Token build: DTCG JSON (src/*.json) -> dist/tokens.css, dist/theme.css, dist/tokens.ts
 *
 *  Two layers: src/primitives.json (`palette.*`, raw values) and src/semantic.json (`color.*`, aliases of
 *  primitives with DTCG `{}` references). Type, radius, spacing, elevation and layout live in their own files.
 *
 *  tokens.css  every token as a CSS custom property on :root, prefixed `--pll-`. Aliases are emitted as
 *              `var(--pll-...)`, so the semantic layer stays linked to the primitives.
 *  theme.css   a Tailwind v4 `@theme` block that maps the tokens onto Tailwind namespaces, resets the default
 *              palette/type/radius/shadow/font scales, and defines the runtime team-color utilities.
 *  tokens.ts   the resolved tree as a typed `as const` object, CSS variable names, and a flat `tokenList`
 *              (used by the Storybook "Foundations/Tokens" page so docs never drift).
 *
 *  Extensions understood (all under `$extensions["com.pll"]`):
 *    alpha       number 0..1. The token is its alias target at that alpha (tints, hairline).
 *    runtimeVar  CSS custom property set at runtime on a scope (team colors). The token value is the fallback.
 *    hostVar     CSS custom property supplied by the host app's font loader (next/font). The first family of the
 *                stack becomes `var(<hostVar>, <family>)`, so the same token works with and without next/font.
 *
 * Run: npm run build -w @pll/tokens   (or `npm run tokens` at the repo root)
 */
import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const PREFIX = 'pll';
const BANNER = '/* Generated by packages/tokens/build.mjs from src/*.json. Do not edit. */\n';
const GROUP_ORDER = ['palette', 'color', 'font', 'text', 'radius', 'spacing', 'elevation', 'layout'];
const GENERIC_FAMILIES = new Set(['serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui', 'ui-sans-serif', 'ui-serif', 'ui-monospace', 'ui-rounded']);

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const pathVar = (parts) => `--${PREFIX}-${parts.map(kebab).join('-')}`;
const varName = (t) => pathVar(t.path);
const ext = (t) => t.$extensions?.['com.pll'] ?? {};
const typeOf = (t) => t.$type ?? t.type;

/** Path of the alias target when the authored value is exactly `{a.b.c}`, else null. */
function aliasOf(t) {
  const o = t.original?.$value;
  const m = typeof o === 'string' ? o.match(/^\{([^{}]+)\}$/) : null;
  return m ? m[1].split('.') : null;
}

const quoteFamily = (f) => (/\s/.test(f) && !GENERIC_FAMILIES.has(f) && !/^['"]/.test(f) ? `'${f}'` : f);
const familyList = (arr) => arr.map(quoteFamily).join(', ');
const pct = (alpha) => Math.round(alpha * 10000) / 100;

function rgba(hex, alpha) {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

const shortLength = (v) => (parseFloat(v) === 0 ? '0' : v);
const shadowCss = (s) =>
  [shortLength(s.offsetX), shortLength(s.offsetY), s.blur, parseFloat(s.spread) === 0 ? null : s.spread, s.color]
    .filter(Boolean)
    .join(' ');

/** The fully resolved value (what a consumer of tokens.ts sees). */
function resolved(t) {
  const v = t.$value ?? t.value;
  const { alpha } = ext(t);
  if (alpha !== undefined) return rgba(v, alpha);
  if (Array.isArray(v)) return familyList(v);
  if (typeOf(t) === 'shadow') return shadowCss(v);
  return v;
}

/** The value written to tokens.css (aliases stay var() references). */
function cssValue(t) {
  const v = t.$value ?? t.value;
  const { alpha, hostVar } = ext(t);
  const alias = aliasOf(t);
  const ref = alias ? `var(${pathVar(alias)})` : null;
  if (alpha !== undefined) return `color-mix(in srgb, ${ref ?? v} ${pct(alpha)}%, transparent)`;
  if (hostVar && Array.isArray(v)) return [`var(${hostVar}, ${quoteFamily(v[0])})`, ...v.slice(1).map(quoteFamily)].join(', ');
  if (ref) return ref;
  return String(resolved(t));
}

const sortTokens = (tokens) =>
  [...tokens].sort((a, b) => GROUP_ORDER.indexOf(a.path[0]) - GROUP_ORDER.indexOf(b.path[0]));

/**
 * Where a token lands in Tailwind. `block`: 'theme' (@theme), 'inline' (@theme inline, resolved per element),
 * or null (not exposed as a theme variable). `utility` is the example class shown in the docs.
 */
function themeEntry(t) {
  const [group, ...rest] = t.path;
  const key = rest.map(kebab).join('-');
  const v = `var(${varName(t)})`;
  switch (group) {
    case 'color':
      if (rest[0] === 'team') {
        // Resolved on the element, so a team scope can override --team-primary / --team-secondary.
        return { block: 'inline', decl: `--color-${key}: var(${ext(t).runtimeVar}, ${v});`, utility: `bg-${key}` };
      }
      return { block: 'theme', decl: `--color-${key}: ${v};`, utility: `bg-${key}` };
    case 'radius':
      return { block: 'theme', decl: `--radius-${key}: ${v};`, utility: `rounded-${key}` };
    case 'elevation':
      return { block: 'theme', decl: `--shadow-elevation-${key}: ${v};`, utility: `shadow-elevation-${key}` };
    case 'font':
      return { block: 'theme', decl: `--font-${kebab(rest[1])}: ${v};`, utility: `font-${kebab(rest[1])}` };
    case 'layout':
      return rest[0] === 'pageMax'
        ? { block: 'theme', decl: `--container-page: ${v};`, utility: 'max-w-page' }
        : { block: null, utility: null };
    case 'spacing':
      // No theme variable: spacing uses Tailwind's 4px multiplier (`--spacing`), see theme.css.
      return { block: null, utility: `p-${parseFloat(t.$value) / 4}` };
    case 'text': {
      const [style, prop] = [kebab(rest[0]), rest[1]];
      const map = {
        fontSize: [`--text-${style}`, `text-${style}`],
        lineHeight: [`--text-${style}--line-height`, null],
        fontWeight: [`--text-${style}--font-weight`, null],
        letterSpacing: [`--text-${style}--letter-spacing`, null],
      };
      const hit = map[prop];
      return hit ? { block: 'theme', decl: `${hit[0]}: ${v};`, utility: hit[1] } : { block: null, utility: null };
    }
    default:
      return { block: null, utility: null };
  }
}

StyleDictionary.registerTransform({
  name: 'pll/name/css-var',
  type: 'name',
  transform: (token) => varName(token).slice(2),
});
StyleDictionary.registerTransformGroup({ name: 'pll/css', transforms: ['pll/name/css-var'] });

StyleDictionary.registerFormat({
  name: 'pll/css-variables',
  format: ({ dictionary }) => {
    const out = [];
    let group = null;
    for (const t of sortTokens(dictionary.allTokens)) {
      if (t.path[0] !== group) {
        group = t.path[0];
        out.push(`${out.length ? '\n' : ''}  /* ${group} */`);
      }
      out.push(`  ${varName(t)}: ${cssValue(t)};`);
    }
    return `${BANNER}:root {\n${out.join('\n')}\n}\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'pll/tailwind-theme',
  format: ({ dictionary }) => {
    const theme = [];
    const inline = [];
    const utilityRules = [];
    for (const t of sortTokens(dictionary.allTokens)) {
      const e = themeEntry(t);
      if (e.block === 'theme') theme.push(`  ${e.decl}`);
      if (e.block === 'inline') inline.push(`  ${e.decl}`);

      // Text styles: Tailwind's --text-* only carries size/line-height/weight/tracking. The rest of the style
      // (display font family, tabular numerals) rides on a zero-specificity rule, so `font-*` utilities still win.
      if (t.path[0] === 'text') {
        const [style, prop] = [kebab(t.path[1]), t.path[2]];
        if (prop === 'fontFamily' && aliasOf(t)?.join('.') !== 'font.family.sans') {
          utilityRules.push(`  :where(.text-${style}) { font-family: var(${varName(t)}); }`);
        }
        if (prop === 'fontVariantNumeric') {
          utilityRules.push(`  :where(.text-${style}) { font-variant-numeric: ${t.$value}; }`);
        }
      }
    }

    const groupBy = (prefix) => theme.filter((l) => l.trimStart().startsWith(prefix));
    const colors = groupBy('--color-');
    const texts = groupBy('--text-');
    const radii = groupBy('--radius-');
    const shadows = groupBy('--shadow-');
    const fonts = groupBy('--font-');
    const containers = groupBy('--container-');

    return [
      BANNER + '@theme {',
      '  /* Only tokens exist as utilities: Tailwind\'s default palette, type scale, radii, shadows and font',
      '     families are reset. (Font weights, tracking, breakpoints and sizing keep Tailwind\'s defaults.) */',
      '  --color-*: initial;',
      ...colors,
      '',
      '  --text-*: initial;',
      ...texts,
      '',
      '  --font-*: initial;',
      ...fonts,
      '',
      '  --radius-*: initial;',
      ...radii,
      '',
      '  --shadow-*: initial;',
      ...shadows,
      '',
      '  /* Spacing: Tailwind\'s 4px multiplier is kept, so utilities are N = px / 4. The approved scale',
      '     (2, 4, 8, 10, 12, 16, 20, 24, 32, 40) is p/m/gap/space-{0.5, 1, 2, 2.5, 3, 4, 5, 6, 8, 10}.',
      '     Other steps (1.5, 3.5, 7, 9, 11, 12...) exist in Tailwind but are off-scale: do not use them. */',
      '  --spacing: 0.25rem;',
      '',
      ...containers,
      '}',
      '',
      '/* Team colors: `bg-team-primary`, `text-team-secondary`, `border-team-primary`...',
      '   Inline so the var() is resolved on the element: a parent can set',
      '   style={{ \'--team-primary\': team.colors.primary }} and its subtree picks it up. Without it, the neutral fallback applies. */',
      '@theme inline {',
      ...inline,
      '}',
      '',
      '/* Text-style extras that Tailwind\'s --text-* variables cannot carry. */',
      '@layer utilities {',
      ...utilityRules,
      '}',
      '',
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'pll/typescript',
  format: ({ dictionary }) => {
    const tree = {};
    const vars = {};
    const list = [];
    for (const t of sortTokens(dictionary.allTokens)) {
      const value = resolved(t);
      let node = tree;
      t.path.slice(0, -1).forEach((p) => (node = node[p] ??= {}));
      node[t.path.at(-1)] = value;
      const dotted = t.path.join('.');
      vars[dotted] = varName(t);
      const alias = aliasOf(t);
      list.push({
        path: dotted,
        cssVar: varName(t),
        type: typeOf(t) ?? null,
        value,
        ref: alias ? alias.join('.') : null,
        alpha: ext(t).alpha ?? null,
        runtimeVar: ext(t).runtimeVar ?? null,
        description: t.$description ?? t.description ?? null,
        utility: themeEntry(t).utility,
      });
    }
    return [
      '// Generated by packages/tokens/build.mjs from src/*.json. Do not edit.',
      '// Values are fully resolved: aliases are followed, alpha tokens are rgba(), shadows are CSS strings,',
      '// font stacks are the plain stack (the CSS output additionally wires the host font variable).',
      `export const tokens = ${JSON.stringify(tree, null, 2)} as const;`,
      '',
      '/** Dotted token path -> CSS custom property name (defined in tokens.css). */',
      `export const cssVars = ${JSON.stringify(vars, null, 2)} as const;`,
      '',
      'export interface TokenEntry {',
      '  /** Dotted path, e.g. `color.surface.card`. */',
      '  path: string;',
      '  cssVar: string;',
      '  /** DTCG `$type`. */',
      '  type: string | null;',
      '  /** Resolved value: hex / rgba() for colors, CSS string for dimensions, shadows and font stacks. */',
      '  value: string | number;',
      '  /** Dotted path of the token this one aliases, if any. */',
      '  ref: string | null;',
      '  alpha: number | null;',
      '  /** Runtime CSS variable that overrides the token (team colors). */',
      '  runtimeVar: string | null;',
      '  description: string | null;',
      '  /** Example Tailwind utility for the token, if it has one. */',
      '  utility: string | null;',
      '}',
      '',
      '/** Every token, flat and in source order. The Storybook token docs render from this. */',
      `export const tokenList: readonly TokenEntry[] = ${JSON.stringify(list, null, 2)};`,
      '',
      'export type Tokens = typeof tokens;',
      'export type TokenPath = keyof typeof cssVars;',
      '/** `var(--pll-...)` reference for a token path. */',
      'export const cssVar = (path: TokenPath): string => `var(${cssVars[path]})`;',
      '',
    ].join('\n');
  },
});

const sd = new StyleDictionary({
  usesDtcg: true,
  source: [path.join(here, 'src/*.json')],
  log: { verbosity: 'default' },
  platforms: {
    web: {
      transformGroup: 'pll/css',
      buildPath: path.join(here, 'dist') + '/',
      files: [
        { destination: 'tokens.css', format: 'pll/css-variables' },
        { destination: 'theme.css', format: 'pll/tailwind-theme' },
        { destination: 'tokens.ts', format: 'pll/typescript' },
      ],
    },
  },
});

await sd.buildAllPlatforms();
