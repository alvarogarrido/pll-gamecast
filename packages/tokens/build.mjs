/**
 * Token build: DTCG JSON (src/*.json) -> dist/tokens.css, dist/theme.css, dist/tokens.ts
 *
 *  tokens.css  every token as a CSS custom property on :root, prefixed `--pll-`
 *  theme.css   a Tailwind v4 `@theme` block that aliases those variables onto Tailwind's
 *              namespaces (--color-*, --radius-*, --font-*, --text-*, --container-*)
 *  tokens.ts   the same resolved tree as a typed `as const` object + CSS variable names
 *
 * Run: npm run build -w @pll/tokens   (or `npm run tokens` at the repo root)
 */
import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const PREFIX = 'pll';
const BANNER = '/* Generated by packages/tokens/build.mjs from src/*.json. Do not edit. */\n';

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const varName = (token) => `--${PREFIX}-${token.path.map(kebab).join('-')}`;
const ref = (token) => `var(${varName(token)})`;
const valueOf = (token) => String(token.$value ?? token.value);

StyleDictionary.registerTransform({
  name: 'pll/name/css-var',
  type: 'name',
  transform: (token) => varName(token).slice(2),
});
StyleDictionary.registerTransformGroup({ name: 'pll/css', transforms: ['pll/name/css-var'] });

StyleDictionary.registerFormat({
  name: 'pll/css-variables',
  format: ({ dictionary }) => {
    const lines = dictionary.allTokens.map((t) => `  ${varName(t)}: ${valueOf(t)};`);
    return `${BANNER}:root {\n${lines.join('\n')}\n}\n`;
  },
});

StyleDictionary.registerFormat({
  name: 'pll/tailwind-theme',
  format: ({ dictionary }) => {
    const out = [];
    const colors = [];
    const radii = [];
    const fonts = [];
    const texts = [];
    const containers = [];

    for (const t of dictionary.allTokens) {
      const [group, ...rest] = t.path;
      const key = rest.map(kebab).join('-');
      if (group === 'color') colors.push(`  --color-${key}: ${ref(t)};`);
      else if (group === 'radius') radii.push(`  --radius-${key}: ${ref(t)};`);
      else if (group === 'font' && rest[0] === 'family') fonts.push(`  --font-${kebab(rest[1])}: ${ref(t)};`);
      else if (group === 'layout' && rest[0] === 'pageMax') containers.push(`  --container-page: ${ref(t)};`);
      else if (group === 'text') {
        const [style, prop] = rest.map(kebab);
        const map = {
          size: `--text-${style}`,
          leading: `--text-${style}--line-height`,
          weight: `--text-${style}--font-weight`,
          tracking: `--text-${style}--letter-spacing`,
        };
        if (map[prop]) texts.push(`  ${map[prop]}: ${ref(t)};`);
      }
    }

    out.push(BANNER + '@theme {');
    out.push('  /* Only token colors/radii exist as utilities: no stray default palette. */');
    out.push('  --color-*: initial;', ...colors, '');
    out.push('  --radius-*: initial;', ...radii, '');
    out.push(...fonts, '');
    out.push(...texts, '');
    out.push(...containers);
    out.push('}\n');
    return out.join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'pll/typescript',
  format: ({ dictionary }) => {
    const tree = {};
    const vars = {};
    for (const t of dictionary.allTokens) {
      let node = tree;
      t.path.slice(0, -1).forEach((p) => (node = node[p] ??= {}));
      node[t.path.at(-1)] = t.$value ?? t.value;
      vars[t.path.join('.')] = varName(t);
    }
    return [
      '// Generated by packages/tokens/build.mjs from src/*.json. Do not edit.',
      `export const tokens = ${JSON.stringify(tree, null, 2)} as const;`,
      '',
      '/** Dotted token path -> CSS custom property name (defined in tokens.css). */',
      `export const cssVars = ${JSON.stringify(vars, null, 2)} as const;`,
      '',
      'export type Tokens = typeof tokens;',
      'export type TokenPath = keyof typeof cssVars;',
      '/** `var(--pll-...)` reference for a token path. */',
      'export const cssVar = (path: TokenPath): string => `var(${cssVars[path]})`;',
      '',
    ].join('\n');
  },
});

const sd = new StyleDictionary({
  usesDtcg: true,
  source: [path.join(here, 'src/*.json')],
  log: { verbosity: 'default' },
  platforms: {
    web: {
      transformGroup: 'pll/css',
      buildPath: path.join(here, 'dist') + '/',
      files: [
        { destination: 'tokens.css', format: 'pll/css-variables' },
        { destination: 'theme.css', format: 'pll/tailwind-theme' },
        { destination: 'tokens.ts', format: 'pll/typescript' },
      ],
    },
  },
});

await sd.buildAllPlatforms();
