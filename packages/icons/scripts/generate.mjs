#!/usr/bin/env node
// Turns src/svg/*.svg (+ src/svg/network/*.svg) into typed React components in src/generated.
// No dependencies: a tiny SVG -> JSX converter is enough because the SVGs are svgo-normalised
// (only <path>, <g>, <defs>, <linearGradient>, <stop>).
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = join(root, 'src/svg');
const outDir = join(root, 'src/generated');
const BANNER = '// AUTO-GENERATED by scripts/generate.mjs from src/svg. Do not edit by hand.\n';

const pascal = (s) => s.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const camel = (a) => a.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

/** Parse an svgo-normalised SVG into { attrs, inner }. */
function parseSvg(src) {
  const m = src.trim().match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/);
  if (!m) throw new Error('not a plain <svg> document');
  const attrs = Object.fromEntries([...m[1].matchAll(/([\w:-]+)="([^"]*)"/g)].map((x) => [x[1], x[2]]));
  return { attrs, inner: m[2] };
}

/** Convert SVG markup (no text nodes) to JSX markup. */
function toJsx(inner) {
  return inner.replace(/<(\/?)([A-Za-z][\w]*)([^>]*?)(\/?)>/g, (_, close, tag, attrs, selfClose) => {
    if (close) return `</${tag}>`;
    const a = [...attrs.matchAll(/([\w:-]+)="([^"]*)"/g)]
      .map((x) => `${camel(x[1])}="${x[2]}"`)
      .join(' ');
    return `<${tag}${a ? ' ' + a : ''}${selfClose ? ' /' : ''}>`;
  });
}

/** An icon is multi-colour if it carries a literal colour (not currentColor/none/url()). */
function isMulticolor(inner) {
  return [...inner.matchAll(/\b(?:fill|stroke)="([^"]+)"/g)].some(
    ([, v]) => !/^(currentColor|none|url\(.*\))$/.test(v),
  );
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// ---- Icons ---------------------------------------------------------------
const iconFiles = readdirSync(svgDir).filter((f) => f.endsWith('.svg')).sort();
const iconNames = [];
const multicolor = [];
for (const file of iconFiles) {
  const name = file.replace(/\.svg$/, '');
  const { attrs, inner } = parseSvg(readFileSync(join(svgDir, file), 'utf8'));
  if (attrs.viewBox !== '0 0 24 24') throw new Error(`${file}: expected viewBox 0 0 24 24, got ${attrs.viewBox}`);
  if (isMulticolor(inner)) multicolor.push(name);
  const Comp = pascal(name) + 'Icon';
  writeFileSync(
    join(outDir, `${Comp}.tsx`),
    `${BANNER}import { createIcon } from '../createIcon';\n\n` +
      `export const ${Comp} = createIcon('${Comp}', (\n  <>${toJsx(inner)}</>\n));\n`,
  );
  iconNames.push(name);
}

writeFileSync(
  join(outDir, 'index.ts'),
  BANNER + iconNames.map((n) => `export { ${pascal(n)}Icon } from './${pascal(n)}Icon';`).join('\n') + '\n',
);

writeFileSync(
  join(outDir, 'icons.ts'),
  BANNER +
    `import type { IconComponent } from '../types';\n` +
    iconNames.map((n) => `import { ${pascal(n)}Icon } from './${pascal(n)}Icon';`).join('\n') +
    `\n\n/** Every icon name, kebab-case. \`-filled\` marks the Filled style; the rest are Regular / single-style. */\n` +
    `export const iconNames = [\n${iconNames.map((n) => `  '${n}',`).join('\n')}\n] as const;\n\n` +
    `export type IconName = (typeof iconNames)[number];\n\n` +
    `/** Intentionally multi-colour glyphs: they ignore \`currentColor\`. */\n` +
    `export const multicolorIcons: readonly IconName[] = [${multicolor.map((n) => `'${n}'`).join(', ')}];\n\n` +
    `export const icons: Record<IconName, IconComponent> = {\n${iconNames
      .map((n) => `  '${n}': ${pascal(n)}Icon,`)
      .join('\n')}\n};\n`,
);

// ---- Network logos ---------------------------------------------------------
const netDir = join(svgDir, 'network');
const netFiles = readdirSync(netDir).filter((f) => f.endsWith('.svg')).sort();
const networks = {};
for (const file of netFiles) {
  const m = file.match(/^(.+)-(white|color)\.svg$/);
  if (!m) throw new Error(`network file must be <network>-<white|color>.svg: ${file}`);
  const [, id, variant] = m;
  const { attrs, inner } = parseSvg(readFileSync(join(netDir, file), 'utf8'));
  const [, , w, h] = attrs.viewBox.split(' ').map(Number);
  (networks[id] ??= {})[variant] = { viewBox: attrs.viewBox, width: w, height: h, jsx: toJsx(inner) };
}
const labels = { abc: 'ABC', espn: 'ESPN', 'espn-plus': 'ESPN+', espn2: 'ESPN2', 'espn-app': 'ESPN App' };
const ids = Object.keys(networks).sort();
for (const id of ids) {
  for (const v of ['white', 'color']) if (!networks[id][v]) throw new Error(`network ${id} is missing the ${v} variant`);
  if (!labels[id]) throw new Error(`add a label for network "${id}" in scripts/generate.mjs`);
}
writeFileSync(
  join(outDir, 'networkLogos.tsx'),
  BANNER +
    `import type { ReactNode } from 'react';\n\n` +
    `export const networkIds = [${ids.map((i) => `'${i}'`).join(', ')}] as const;\n` +
    `export type NetworkId = (typeof networkIds)[number];\n` +
    `export const networkVariants = ['white', 'color'] as const;\n` +
    `export type NetworkVariant = (typeof networkVariants)[number];\n\n` +
    `export const networkLabels: Record<NetworkId, string> = {\n${ids.map((i) => `  '${i}': '${labels[i]}',`).join('\n')}\n};\n\n` +
    `export interface NetworkLogoArt { viewBox: string; width: number; height: number; children: ReactNode }\n\n` +
    `export const networkLogos: Record<NetworkId, Record<NetworkVariant, NetworkLogoArt>> = {\n` +
    ids
      .map(
        (id) =>
          `  '${id}': {\n` +
          ['white', 'color']
            .map((v) => {
              const n = networks[id][v];
              return `    ${v}: { viewBox: '${n.viewBox}', width: ${n.width}, height: ${n.height}, children: <>${n.jsx}</> },`;
            })
            .join('\n') +
          `\n  },`,
      )
      .join('\n') +
    `\n};\n`,
);

console.log(`@pll/icons: ${iconNames.length} icons (${multicolor.length} multicolor: ${multicolor.join(', ')}), ${ids.length} networks x 2 variants`);
